"""Writes src/burstlimit_key_icons.inc: the keyboard key icons the game's button prompts show
when it is played on the keyboard (src/burstlimit_buttons.cpp, button_icons = keyboard / auto),
as the PNG files' own bytes, keyed by the key names of the keybind_* settings ("J", "Space",
"Return", "Up"...).

The icons are from Xelu's Free Controller & Keyboard Prompts (Nicolae "Xelu" Berbece, Those
Awesome Guys), public domain (CC0) - the same pack as the controller icons
(scripts/make_button_icons.py): https://thoseawesomeguys.com/prompts/ . The light keys
("Keyboard Light" in the pack's "Prompts Export 256.zip", 256x256); the F keys, which that
export doesn't have, from the pack's 100x100 "Keyboard & Mouse/Light" files.

    python scripts/make_key_icons.py <folder of the pack: Prompts Export 256.zip, Keyboard & Mouse\\>
"""
import os
import sys
import zipfile

ZIP_256 = "Prompts Export 256.zip"

# keybind key name -> number of the "Keyboard Light/KeyLightNNNN.png" file.
KEYS_256 = {
    "Up": 81, "Right": 82, "Down": 83, "Left": 84,
    "Q": 85, "W": 86, "E": 87, "R": 88, "T": 89, "Y": 90, "U": 91, "I": 92, "O": 93, "P": 94,
    "A": 95, "S": 96, "D": 97, "F": 98, "G": 99, "H": 100, "J": 101, "K": 102, "L": 103,
    "Z": 104, "X": 105, "C": 106, "V": 107, "B": 108, "N": 109, "M": 110,
    "0": 111, "1": 112, "2": 113, "3": 114, "4": 115, "5": 116, "6": 117, "7": 118, "8": 119,
    "9": 120,
    "Backtick": 121, "Insert": 122, "Delete": 123, "End": 124, "Home": 125, "PageDown": 126,
    "PageUp": 127, "Minus": 128, "Plus": 129, "Backslash": 130, "Slash": 131, "Semicolon": 132,
    "Quote": 133, "LBracket": 134, "RBracket": 135, "Comma": 136, "Period": 137,
    "NumpadStar": 138, "Escape": 139, "Shift": 140, "Control": 141, "Alt": 142, "Tab": 143,
    "CapsLock": 144, "Backspace": 145, "Space": 148, "Return": 149,
    "LMB": 69, "RMB": 70, "MMB": 71,
}
# Keys drawn with another key's icon (the numpad digits as digits...).
ALIASES = {f"Numpad{d}": str(d) for d in range(10)}
ALIASES.update({"NumpadEnter": "Return", "NumpadPlus": "Plus", "NumpadMinus": "Minus",
                "NumpadSlash": "Slash"})
# 100x100 files for keys the 256 export doesn't have.
KEYS_100 = {f"F{n}": f"F{n}_Key_Light.png" for n in range(1, 13)}
KEYS_100.update({"PrintScreen": "Print_Screen_Key_Light.png", "NumLock": "Num_Lock_Key_Light.png"})
BLANK_100 = "Blank_White_Normal.png"  # a key with no icon of its own


def c_array(name, data):
    lines = [f"constexpr uint8_t {name}[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    pack = sys.argv[1] if len(sys.argv) > 1 else r"C:\rex\_tools\xelu_prompts"
    out_path = os.path.join(os.path.dirname(__file__), "..", "src", "burstlimit_key_icons.inc")
    files = {}
    with zipfile.ZipFile(os.path.join(pack, ZIP_256)) as archive:
        for key, number in KEYS_256.items():
            files[key] = archive.read(f"Keyboard Light/KeyLight{number:04d}.png")
    light = os.path.join(pack, "Keyboard & Mouse", "Light")
    for key, name in KEYS_100.items():
        with open(os.path.join(light, name), "rb") as f:
            files[key] = f.read()
    with open(os.path.join(pack, "Keyboard & Mouse", "Blanks", BLANK_100), "rb") as f:
        blank = f.read()

    parts = [
        "// Generated by scripts/make_key_icons.py - Xelu's Free Controller & Keyboard Prompts,",
        "// public domain (CC0): https://thoseawesomeguys.com/prompts/ (light keys).",
        "",
    ]
    names = {}
    for i, (key, data) in enumerate(sorted(files.items())):
        names[key] = f"kKeyIcon{i}"
        parts.append(f"// {key}")
        parts.append(c_array(names[key], data))
    parts.append(c_array("kKeyIconBlank", blank))
    parts.append("")
    parts.append("struct KeyIconFile {")
    parts.append("  const char* key;")
    parts.append("  const uint8_t* data;")
    parts.append("  size_t size;")
    parts.append("};")
    parts.append("constexpr KeyIconFile kKeyIconFiles[] = {")
    for key in sorted(files):
        parts.append(f'    {{"{key}", {names[key]}, sizeof({names[key]})}},')
    for key, target in sorted(ALIASES.items()):
        parts.append(f'    {{"{key}", {names[target]}, sizeof({names[target]})}},')
    parts.append("};")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(parts) + "\n")
    print(f"{len(files)} key icons ({sum(len(d) for d in files.values())} bytes) -> {out_path}")


if __name__ == "__main__":
    main()
